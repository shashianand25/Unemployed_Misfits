import React, { useState } from 'react';
import { useAppStore, useAppDispatch } from '../store/useAppStore';
import { DEMO_ANALYSIS } from '../data/demoData';

const C = {
  bg: '#0a0a0f', surface: '#12121a', surface2: '#1a1a2e', border: '#2a2a3e',
  text: '#f0f0ff', textSec: '#8888aa', violet: '#7c3aed', blue: '#3b82f6',
  green: '#10b981', orange: '#f59e0b',
};

const SKILL_EVIDENCE = [
  { name: 'Python', status: 'Demonstrated', color: C.green, desc: 'Used in core project implementation' },
  { name: 'Redis', status: 'Learning', color: C.blue, desc: 'Currently building Redis integration' },
  { name: 'Docker', status: 'Learning', color: C.blue, desc: 'Containerisation milestone in progress' },
];

const STATUS_INFO = [
  { label: 'Learning', color: C.blue, desc: 'You\'re actively developing this skill in your project' },
  { label: 'Demonstrated', color: C.green, desc: 'You\'ve used this skill in a completed project component' },
  { label: 'Verified', color: C.orange, desc: 'An expert has reviewed and confirmed your proficiency' },
];

export default function PortfolioPage() {
  const dispatch = useAppDispatch();
  const { jobAnalysis, projectGithubUrls, completedMilestones } = useAppStore();
  const analysis = jobAnalysis || DEMO_ANALYSIS;
  const project = analysis.recommendedProject;
  const milestones = project.milestones;
  const completedCount = milestones.filter(m => completedMilestones.includes(m.id)).length;
  const githubUrl = projectGithubUrls[project.id] || '';
  const [githubInput, setGithubInput] = useState(githubUrl);
  const [editingGithub, setEditingGithub] = useState(false);
  const [showSummary, setShowSummary] = useState(false);

  const saveGithub = () => {
    dispatch({ type: 'SET_GITHUB_URL', payload: { projectId: project.id, url: githubInput } });
    setEditingGithub(false);
  };

  const summaryText = `# ${project.title}

## About
${project.description}

## Technologies
${project.technologies.join(', ')}

## Progress
${completedCount} of ${milestones.length} milestones completed.

## Skills Demonstrated
- Python: Demonstrated through core project implementation
- Redis: Learning — building the queue integration layer
- Docker: Learning — containerisation in progress

## Repository
${githubInput || '[GitHub URL not set yet]'}

---
*Portfolio generated by Unemployed Misfits*`;

  return (
    <div style={{ fontFamily: "'Inter', system-ui, sans-serif" }}>
      <div style={{ marginBottom: 32 }}>
        <h1 style={{ fontSize: 32, fontWeight: 800, color: C.text, marginBottom: 8 }}>Show What You Can Actually Build.</h1>
        <p style={{ color: C.textSec, fontSize: 16 }}>Your portfolio is your proof — here's what you're building.</p>
      </div>

      {/* Project portfolio card */}
      <div style={{ background: C.surface, border: `1px solid ${C.border}`, borderRadius: 16, padding: 28, marginBottom: 24 }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', flexWrap: 'wrap', gap: 16, marginBottom: 24 }}>
          <div>
            <div style={{ fontSize: 12, color: C.textSec, fontWeight: 600, textTransform: 'uppercase', letterSpacing: 1, marginBottom: 8 }}>Portfolio Project</div>
            <h2 style={{ fontSize: 22, fontWeight: 800, marginBottom: 12 }}>{project.title}</h2>
            <div style={{ display: 'flex', flexWrap: 'wrap', gap: 8 }}>
              {project.technologies.map(t => (
                <span key={t} style={{ background: 'rgba(124,58,237,0.15)', color: '#a855f7', border: '1px solid rgba(124,58,237,0.3)', borderRadius: 20, padding: '4px 12px', fontSize: 12, fontWeight: 500 }}>{t}</span>
              ))}
            </div>
          </div>
          <div style={{ background: `${C.green}15`, borderRadius: 10, padding: '12px 20px', textAlign: 'center' }}>
            <div style={{ fontSize: 28, fontWeight: 800, color: C.green }}>{completedCount}/{milestones.length}</div>
            <div style={{ fontSize: 12, color: C.textSec }}>Milestones</div>
          </div>
        </div>

        {/* Evidence checklist */}
        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(240px, 1fr))', gap: 12 }}>
          {[
            { label: 'Project description', done: true },
            { label: 'README documentation', done: true },
            { label: 'Architecture diagram', done: false },
            { label: `Completed milestones (${completedCount}/${milestones.length})`, done: completedCount > 0 },
            { label: 'Demo link', done: false },
          ].map((item, i) => (
            <div key={i} style={{ display: 'flex', alignItems: 'center', gap: 10, padding: '10px 14px', background: C.surface2, border: `1px solid ${item.done ? `${C.green}30` : C.border}`, borderRadius: 10 }}>
              <span style={{ fontSize: 18, color: item.done ? C.green : C.textSec }}>{item.done ? '✅' : '⏳'}</span>
              <span style={{ fontSize: 14, color: item.done ? C.text : C.textSec }}>{item.label}</span>
            </div>
          ))}
          {/* GitHub repo - editable */}
          <div style={{ display: 'flex', alignItems: 'center', gap: 10, padding: '10px 14px', background: C.surface2, border: `1px solid ${githubInput ? `${C.green}30` : C.border}`, borderRadius: 10 }}>
            <span style={{ fontSize: 18 }}>{githubInput ? '✅' : '📂'}</span>
            {editingGithub ? (
              <div style={{ flex: 1, display: 'flex', gap: 8 }}>
                <input value={githubInput} onChange={e => setGithubInput(e.target.value)} placeholder="https://github.com/..."
                  style={{ flex: 1, background: C.border, border: 'none', borderRadius: 6, padding: '4px 8px', color: C.text, fontSize: 12, outline: 'none' }} />
                <button onClick={saveGithub} style={{ background: C.violet, border: 'none', color: 'white', padding: '4px 10px', borderRadius: 6, fontSize: 12, cursor: 'pointer' }}>Save</button>
              </div>
            ) : (
              <div style={{ flex: 1, display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                <span style={{ fontSize: 13, color: githubInput ? C.text : C.textSec }}>{githubInput || 'GitHub repo link'}</span>
                <button onClick={() => setEditingGithub(true)} style={{ background: 'none', border: 'none', color: C.violet, fontSize: 12, cursor: 'pointer' }}>Edit</button>
              </div>
            )}
          </div>
        </div>
      </div>

      {/* Skill evidence */}
      <div style={{ background: C.surface, border: `1px solid ${C.border}`, borderRadius: 16, padding: 28, marginBottom: 24 }}>
        <div style={{ fontSize: 15, fontWeight: 700, marginBottom: 20 }}>Skill Evidence</div>
        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(220px, 1fr))', gap: 16, marginBottom: 24 }}>
          {SKILL_EVIDENCE.map((s, i) => (
            <div key={i} style={{ background: C.surface2, border: `1px solid ${C.border}`, borderRadius: 12, padding: 20 }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 10 }}>
                <span style={{ fontSize: 16, fontWeight: 700 }}>{s.name}</span>
                <span style={{ background: `${s.color}20`, color: s.color, border: `1px solid ${s.color}30`, borderRadius: 20, padding: '3px 10px', fontSize: 11, fontWeight: 600 }}>{s.status}</span>
              </div>
              <p style={{ fontSize: 13, color: C.textSec, lineHeight: 1.5 }}>{s.desc}</p>
            </div>
          ))}
        </div>

        {/* Status legend */}
        <div style={{ background: C.surface2, border: `1px solid ${C.border}`, borderRadius: 10, padding: 16 }}>
          <div style={{ fontSize: 12, fontWeight: 600, color: C.textSec, textTransform: 'uppercase', letterSpacing: 1, marginBottom: 12 }}>Status Legend</div>
          <div style={{ display: 'flex', gap: 24, flexWrap: 'wrap' }}>
            {STATUS_INFO.map((s, i) => (
              <div key={i} style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                <div style={{ width: 10, height: 10, borderRadius: '50%', background: s.color }} />
                <div>
                  <span style={{ fontSize: 13, fontWeight: 600, color: s.color }}>{s.label}</span>
                  <span style={{ fontSize: 12, color: C.textSec }}> — {s.desc}</span>
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>

      {/* Disclaimer */}
      <div style={{ background: 'rgba(245,158,11,0.08)', border: '1px solid rgba(245,158,11,0.2)', borderRadius: 10, padding: 16, marginBottom: 24, fontSize: 13, color: C.orange }}>
        ⚠️ Demo verification status only — real verification requires project review by a qualified assessor.
      </div>

      {/* Generate summary button */}
      <button onClick={() => setShowSummary(!showSummary)} style={{ background: `linear-gradient(135deg, ${C.violet}, #6d28d9)`, border: 'none', color: 'white', padding: '14px 28px', borderRadius: 12, fontSize: 16, fontWeight: 700, cursor: 'pointer', marginBottom: 20, boxShadow: '0 4px 24px rgba(124,58,237,0.4)' }}>
        {showSummary ? 'Hide Portfolio Summary' : 'Generate Portfolio Summary'}
      </button>

      {showSummary && (
        <div style={{ background: C.surface2, border: `1px solid ${C.border}`, borderRadius: 14, padding: 24 }}>
          <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: 12 }}>
            <div style={{ fontSize: 14, fontWeight: 700, color: '#a855f7' }}>📄 Generated Portfolio Summary</div>
            <button onClick={() => navigator.clipboard.writeText(summaryText)} style={{ background: 'none', border: `1px solid ${C.border}`, color: C.textSec, padding: '4px 12px', borderRadius: 6, fontSize: 12, cursor: 'pointer' }}>Copy</button>
          </div>
          <pre style={{ color: C.text, fontSize: 13, lineHeight: 1.7, whiteSpace: 'pre-wrap', margin: 0, fontFamily: 'inherit' }}>{summaryText}</pre>
        </div>
      )}
    </div>
  );
}
